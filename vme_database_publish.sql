-- ----------------------------------------------------------------------------
-- 1. Table: users
-- ----------------------------------------------------------------------------
CREATE TABLE `users` (
  `id` VARCHAR(64) NOT NULL,
  `registration_id` VARCHAR(32) NULL UNIQUE,
  `full_name` VARCHAR(100) NOT NULL,
  `username` VARCHAR(50) NOT NULL UNIQUE,
  `email` VARCHAR(255) NOT NULL UNIQUE,
  `phone` VARCHAR(25) NOT NULL UNIQUE,
  `password_hash` VARCHAR(255) NOT NULL,
  `password_salt` VARCHAR(64) NOT NULL,
  `role` ENUM('customer', 'mechanic', 'electrician') NOT NULL DEFAULT 'customer',
  `latitude` DECIMAL(10, 7) NULL,
  `longitude` DECIMAL(10, 7) NULL,
  `email_verified` TINYINT(1) NOT NULL DEFAULT 0,
  `created_at` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  INDEX `idx_users_role` (`role`),
  INDEX `idx_users_coords` (`latitude`, `longitude`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 2. Table: technician_profiles
-- ----------------------------------------------------------------------------
CREATE TABLE `technician_profiles` (
  `user_id` VARCHAR(64) NOT NULL,
  `workshop_name` VARCHAR(150) NOT NULL,
  `experience_years` INT NOT NULL DEFAULT 1,
  `city` VARCHAR(100) NOT NULL DEFAULT 'Bengaluru',
  `service_area_limit` VARCHAR(100) NOT NULL DEFAULT '15 km radius',
  `specializations` TEXT NOT NULL,
  `rating` DECIMAL(3, 2) NOT NULL DEFAULT 4.90,
  `reviews_count` INT NOT NULL DEFAULT 0,
  `status` ENUM('Available', 'On Call', 'Offline') NOT NULL DEFAULT 'Available',
  `created_at` BIGINT NOT NULL,
  PRIMARY KEY (`user_id`),
  CONSTRAINT `fk_tech_profile_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 3. Table: auth_sessions
-- ----------------------------------------------------------------------------
CREATE TABLE `auth_sessions` (
  `token_hash` VARCHAR(64) NOT NULL,
  `user_id` VARCHAR(64) NOT NULL,
  `expires_at` BIGINT NOT NULL,
  `created_at` BIGINT NOT NULL,
  PRIMARY KEY (`token_hash`),
  INDEX `idx_sessions_expires_at` (`expires_at`),
  CONSTRAINT `fk_sessions_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 4. Table: email_verification_codes
-- ----------------------------------------------------------------------------
CREATE TABLE `email_verification_codes` (
  `user_id` VARCHAR(64) NOT NULL,
  `code_hash` VARCHAR(64) NOT NULL,
  `expires_at` BIGINT NOT NULL,
  `attempts` INT NOT NULL DEFAULT 0,
  `sent_at` BIGINT NOT NULL,
  PRIMARY KEY (`user_id`),
  INDEX `idx_email_verif_expires` (`expires_at`),
  CONSTRAINT `fk_verif_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 5. Table: password_reset_codes
-- ----------------------------------------------------------------------------
CREATE TABLE `password_reset_codes` (
  `user_id` VARCHAR(64) NOT NULL,
  `code_hash` VARCHAR(64) NOT NULL,
  `expires_at` BIGINT NOT NULL,
  `attempts` INT NOT NULL DEFAULT 0,
  `sent_at` BIGINT NOT NULL,
  PRIMARY KEY (`user_id`),
  INDEX `idx_reset_expires` (`expires_at`),
  CONSTRAINT `fk_reset_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
